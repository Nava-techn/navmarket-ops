#!/usr/bin/env bash
# Created in Session 4, lab S4.3: HTTPS on srv01 with my own certificate authority.
# Runs on the WORKSTATION, from the repo root. Safe to run again (idempotent).
#
#  1. CA + server certificate in ~/navmarket-ca (never in Git, never on a server for ca.key)
#  2. Deploys the certificate and an Nginx HTTPS site to srv01
#  3. Trusts the CA on this computer and writes docs/session-04/S4.3-proofs.txt
set -euo pipefail

CA=~/navmarket-ca
HOST=${1:-srv01}
NAMES="www.navmarket.lan navmarket-srv01.navmarket.lan"
P=docs/session-04/S4.3-proofs.txt

mkdir -p "$CA" && chmod 700 "$CA"
# Clean-up of the first attempt: files created by mistake at the repo root
for f in ca.crt ca.key ca.srl navmarket.crt navmarket.csr navmarket.key navmarket-tls.conf; do
  [ -f "$f" ] && mv -n "$f" "$CA/" && echo "moved $f to $CA/"
done
cd "$CA"

# 1. The CA (10 years), created once
[ -f ca.key ] || openssl req -x509 -newkey rsa:4096 -noenc -keyout ca.key -out ca.crt -days 3650 \
  -subj "/CN=NavMarket Lab Root CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign"

# 2. The server certificate (397 days max for browsers), created once
if [ ! -f navmarket.crt ]; then
  openssl req -newkey rsa:2048 -noenc -keyout navmarket.key -out navmarket.csr -subj "/CN=www.navmarket.lan"
  openssl x509 -req -in navmarket.csr -CA ca.crt -CAkey ca.key -CAcreateserial -out navmarket.crt -days 397 \
    -extfile <(printf "subjectAltName=DNS:www.navmarket.lan,DNS:navmarket-srv01.navmarket.lan\nbasicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth")
fi
chmod 600 ca.key navmarket.key

# 3. Nginx site: HTTP -> HTTPS on the lab names, HTTPS with our certificate
cat > navmarket-tls.conf <<NGINX
# Session 4, S4.3. Generated by scripts/tls/s4.3-https-lab-ca.sh
server {
    listen 80;
    server_name $NAMES;
    return 301 https://\$host\$request_uri;
}
server {
    listen 443 ssl;
    server_name $NAMES;
    ssl_certificate     /etc/ssl/navmarket/navmarket.crt;
    ssl_certificate_key /etc/ssl/navmarket/navmarket.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    server_tokens off;
    root __ROOT__;
    index index.html;
    error_page 404 /404.html;
    location / { try_files \$uri \$uri/ =404; }
    include /etc/nginx/navmarket-locations/*.conf;   # S4.5 adds /lb/ here
}
NGINX

scp -q navmarket.crt navmarket.key navmarket-tls.conf "$HOST:/tmp/"
ssh -t "$HOST" 'set -e
R=$(sudo grep -rhoP "^\s*root\s+\K/[^;]*navmarket[^;_]*" /etc/nginx/sites-enabled/ | grep -v __ROOT__ | head -1)
[ -n "$R" ] || { echo "Storefront root not found"; exit 1; }; echo "Storefront root: $R"
sudo install -d -m 755 /etc/ssl/navmarket /etc/nginx/navmarket-locations
sudo install -m 644 /tmp/navmarket.crt /etc/ssl/navmarket/
sudo install -m 600 /tmp/navmarket.key /etc/ssl/navmarket/
sed "s#__ROOT__#$R#" /tmp/navmarket-tls.conf | sudo tee /etc/nginx/sites-available/navmarket-tls >/dev/null
sudo ln -sf /etc/nginx/sites-available/navmarket-tls /etc/nginx/sites-enabled/
rm -f /tmp/navmarket.key /tmp/navmarket.crt /tmp/navmarket-tls.conf
sudo nginx -t && sudo systemctl reload nginx && echo "HTTPS deployed"'

# 4. Proofs (sudo asked here, visibly, before the output goes to the file)
cd - >/dev/null
sudo -v
IP=$(ssh -G "$HOST" | awk '/^hostname /{print $2}')
{
echo "# S4.3 proofs - $(date "+%F %T")"
echo; echo "## 1. The server certificate, signed by my lab CA"
openssl x509 -in "$CA/navmarket.crt" -noout -subject -issuer -ext subjectAltName -enddate
openssl verify -CAfile "$CA/ca.crt" "$CA/navmarket.crt"
echo; echo "## 2. With a trust store that does not contain my CA: curl refuses"
T=$(mktemp -d); openssl req -x509 -newkey rsa:2048 -noenc -keyout "$T/k" -out "$T/other.crt" -subj "/CN=Some other CA" -days 1 2>/dev/null
curl -sS --cacert "$T/other.crt" https://www.navmarket.lan/ -o /dev/null; echo "curl exit code: $? (60 = certificate not trusted)"; rm -rf "$T"
echo; echo "## 3. Trust the CA on this computer"
sudo cp "$CA/ca.crt" /usr/local/share/ca-certificates/navmarket-lab-ca.crt && sudo update-ca-certificates | tail -1
echo; echo "## 4. HTTPS works, without -k"
curl -sI https://www.navmarket.lan/ | head -1
curl -s https://www.navmarket.lan/health.json; echo
echo; echo "## 5. TLS handshake"
echo | openssl s_client -connect www.navmarket.lan:443 -servername www.navmarket.lan 2>/dev/null | grep -E "^subject=|^issuer=|Protocol|Verify return"
echo; echo "## 6. HTTP on the name redirects to HTTPS"
curl -sI http://www.navmarket.lan/ | grep -iE "^HTTP|^Location"
echo; echo "## 7. HTTP by IP still serves the storefront"
curl -sI "http://$IP/" | head -1
} 2>&1 | sed "s/${IP//./\\.}/<VM_IP>/g" > "$P"
cat "$P"
